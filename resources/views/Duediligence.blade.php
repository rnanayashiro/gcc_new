                    株価算定・価値評価
                </div>
                <div class="">
                    事業価値・企業価値・株式価値の評価・算定をいたします。非上場株式の事業価値や株価は、使用目的、売買当事者の関係、将来事業計画の有無等状況に応じて、最適な算定方法をとる必要があります。
